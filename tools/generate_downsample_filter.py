#!/usr/bin/env python3
"""Generate the symmetric 95-tap Blackman FIR for 44100 -> 22050 Hz."""
import math
from pathlib import Path


def main():
    taps = 95
    cutoff = 9500 / 44100
    values = []
    for index in range(taps):
        position = index - (taps - 1) / 2
        sinc = (2 * cutoff if position == 0 else
                math.sin(2 * math.pi * cutoff * position) / (math.pi * position))
        window = (0.42 - 0.5 * math.cos(2 * math.pi * index / (taps - 1))
                  + 0.08 * math.cos(4 * math.pi * index / (taps - 1)))
        values.append(sinc * window)
    total = sum(values)
    coefficients = ',\n'.join(f'    {value / total:.12e}f' for value in values[:48])
    target = Path(__file__).resolve().parents[1] / 'src/radwolf_downsample_coeffs.h'
    target.write_text('/* GPL-3.0-or-later. Generated by tools/generate_downsample_filter.py. */\n'
                      'static const float radwolf_fir_coefficients[48] = {\n'
                      + coefficients + '\n};\n', encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
